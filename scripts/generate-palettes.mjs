// Generates app/m3-palettes.css from lib/m3-seeds.json. Run: npm run palettes
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { Hct, MaterialDynamicColors, SchemeFidelity, argbFromHex, hexFromArgb } from "@material/material-color-utilities";

export const ROLES = [
  "primary", "on-primary", "primary-container", "on-primary-container",
  "secondary", "on-secondary", "secondary-container", "on-secondary-container",
  "tertiary", "on-tertiary", "tertiary-container", "on-tertiary-container",
  "error", "on-error", "error-container", "on-error-container",
  "surface", "on-surface", "surface-variant", "on-surface-variant",
  "surface-container-lowest", "surface-container-low", "surface-container",
  "surface-container-high", "surface-container-highest",
  "inverse-surface", "inverse-on-surface", "inverse-primary",
  "outline", "outline-variant", "scrim", "surface-tint",
];

const camel = (role) => role.replace(/-(\w)/g, (_, c) => c.toUpperCase());

// Fidelity keeps the seed as primary, so lime stays lime (see spec GH-1, "Couleur").
function scheme(hex, isDark) {
  const seed = Hct.fromInt(argbFromHex(hex));
  const s = new SchemeFidelity(seed, isDark, 0);
  const colors = Object.fromEntries(ROLES.map((r) => [r, hexFromArgb(MaterialDynamicColors[camel(r)].getArgb(s))]));
  if (isDark) {
    // Fidelity puts a light seed (lime) in primary-container and pushes dark primary to white;
    // use its own primary palette at fixed tones so the seed stays the visible accent.
    const tone = (t) => hexFromArgb(s.primaryPalette.tone(t));
    Object.assign(colors, {
      primary: tone(Math.max(80, Math.round(seed.tone))),
      "on-primary": tone(20),
      "primary-container": tone(30),
      "on-primary-container": tone(90),
      "inverse-primary": tone(40),
      "surface-tint": tone(80),
    });
  }
  return colors;
}

export function buildPalettes(seeds) {
  return Object.fromEntries(seeds.map(({ id, hex }) => [id, { dark: scheme(hex, true), light: scheme(hex, false) }]));
}

const block = (selector, colors) =>
  `${selector} {\n${Object.entries(colors).map(([r, v]) => `  --md-sys-color-${r}: ${v};`).join("\n")}\n}\n`;

export function toCss(palettes) {
  const [first, ...rest] = Object.keys(palettes);
  let css = "/* Generated by scripts/generate-palettes.mjs — do not edit. Dark is the default theme. */\n";
  // The first seed is the default: it also owns :root so a missing or unknown data-seed renders it.
  css += block(`:root, html[data-seed="${first}"]`, palettes[first].dark);
  css += block(`html[data-theme="light"], html[data-seed="${first}"][data-theme="light"]`, palettes[first].light);
  for (const id of rest) {
    css += block(`html[data-seed="${id}"]`, palettes[id].dark);
    css += block(`html[data-seed="${id}"][data-theme="light"]`, palettes[id].light);
  }
  return css;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const seeds = JSON.parse(readFileSync(new URL("../lib/m3-seeds.json", import.meta.url)));
  writeFileSync(new URL("../app/m3-palettes.css", import.meta.url), toCss(buildPalettes(seeds)));
  console.log("app/m3-palettes.css written");
}
